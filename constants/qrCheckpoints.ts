export const findCheckpointByPayload = (raw: string | null | undefined): QrCheckpoint | null => {
  if (!raw) return null;
  const normalized = raw.trim().toLowerCase();
  return (
    QR_CHECKPOINTS.find((checkpoint) =>
      checkpoint.payloads.some((payload) => payload.toLowerCase() === normalized)
    ) ?? null
  );
};
